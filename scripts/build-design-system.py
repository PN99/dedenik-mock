"""Build the public design-system page and CSS from reviewed source files.

No dependencies, network access, or changes to the WordPress theme are needed.
Run from any directory; --check is the non-mutating CI freshness check.
"""
import argparse
from fractions import Fraction
import html
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'design-system'
REQUIRED_TOKENS = {
    '--navy', '--red', '--cream', '--paper', '--ink', '--muted',
    '--green', '--gold', '--line', '--serif', '--sans',
    '--ratio-graphic', '--ratio-graphic-portrait', '--ratio-photo',
}


def read_json(path):
    if path.is_symlink():
        raise ValueError('Symlink is not a design-system source: ' + path.name)
    return json.loads(path.read_text(encoding='utf-8-sig'))


def token_entries(document):
    entries = []
    names = set()
    for category, items in document['tokens'].items():
        for name, token in items.items():
            css, value = token['css'], token['value']
            if not re.fullmatch(r'--[a-z][a-z0-9-]*', css) or css in names:
                raise ValueError('Invalid or duplicate CSS token: ' + css)
            if not isinstance(value, str) or not value or re.search(r'[;{}<>\r\n]', value):
                raise ValueError('Invalid CSS value for ' + css)
            if not isinstance(token.get('description'), str):
                raise ValueError('Token description is required: ' + css)
            if category == 'color' and not re.fullmatch(r'#[0-9A-Fa-f]{6}', value):
                raise ValueError('Color must be a six-digit hex value: ' + css)
            names.add(css)
            entries.append((category, name, token))
    if REQUIRED_TOKENS - names:
        raise ValueError('Missing required tokens: ' + ', '.join(sorted(REQUIRED_TOKENS - names)))
    return entries


def outputs(source=SOURCE):
    tokens = read_json(source / 'tokens.json')
    system = read_json(source / 'system.json')
    if tokens['version'] != system['version'] or tokens['updated'] != system['updated']:
        raise ValueError('tokens.json and system.json must have the same version and date')
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', tokens['updated']):
        raise ValueError('Use an ISO date (YYYY-MM-DD)')
    entries = token_entries(tokens)
    by_name = {token['css']: token for _, _, token in entries}
    ratio_placeholders = {}
    for key, variable, base_dimension, portrait in (
        ('GRAPHIC', '--ratio-graphic', 600, False),
        ('PORTRAIT', '--ratio-graphic-portrait', 600, True),
        ('PHOTO', '--ratio-photo', 1000, False),
    ):
        parts = by_name[variable]['value'].split('/')
        if len(parts) != 2:
            raise ValueError('Ratio must contain two positive numbers: ' + variable)
        left, right = (Fraction(part.strip()) for part in parts)
        if left <= 0 or right <= 0:
            raise ValueError('Ratios must be positive: ' + variable)
        label = ' : '.join(part.strip().replace('.', ',') for part in parts)
        width = base_dimension if portrait else round(base_dimension * left / right)
        height = round(base_dimension * right / left) if portrait else base_dimension
        ratio_placeholders[key + '_RATIO'] = label
        ratio_placeholders[key + '_CANVAS'] = f'{width} × {height} px'
    for image_format in system['imageFormats']:
        expected = by_name[image_format['token']]['value']
        if re.sub(r'\s+', '', image_format['ratio']) != re.sub(r'\s+', '', expected):
            raise ValueError('Image format differs from its token: ' + image_format['id'])
    css = '/* Generated by scripts/build-design-system.py; edit tokens.json. */\n:root {\n'
    css += ''.join(f"  {token['css']}: {token['value']};\n" for _, _, token in entries)
    css += '}\n'
    swatches, rows = [], []
    esc = lambda value: html.escape(str(value), quote=True)
    for category, name, token in entries:
        variable, value, description = map(esc, (token['css'], token['value'], token['description']))
        rows.append(f'<tr><th scope="row"><code>{variable}</code></th><td><code>{value}</code></td><td>{description}</td></tr>')
        if category == 'color':
            swatches.append(
                f'<article class="swatch"><div class="swatch-color" style="--swatch:{value}"></div>'
                f'<div class="swatch-body"><h3>{esc(token.get("label", name))}</h3><p>{description}</p>'
                f'<button class="copy-token" type="button" data-copy="{variable}" aria-label="Kopírovat {variable}">'
                f'{variable} <span>Kopírovat</span></button><code>{value}</code></div></article>'
            )
    page = (source / 'index.template.html').read_text(encoding='utf-8-sig')
    for key, value in {
        'VERSION': esc(tokens['version']), 'UPDATED': esc(tokens['updated']),
        'TOKEN_SWATCHES': '\n'.join(swatches), 'TOKEN_TABLE': '\n'.join(rows),
        **ratio_placeholders,
    }.items():
        page = page.replace('{{' + key + '}}', value)
    unresolved = re.findall(r'\{\{[A-Z_]+\}\}', page)
    if unresolved:
        raise ValueError('Unknown template placeholders: ' + ', '.join(unresolved))
    if 'Dedeník Design System' not in page:
        raise ValueError('Missing design-system deployment identity')
    return {'tokens.css': css, 'index.html': page.rstrip() + '\n'}, entries


def check_theme(entries):
    stylesheet = (ROOT / 'wp-content/themes/dedenik/assets/css/main.css').read_text(encoding='utf-8-sig')
    actual = dict(re.findall(r'(--[a-z][a-z0-9-]*)\s*:\s*([^;}]+)', stylesheet))
    normalize = lambda value: re.sub(r'\s+', '', value)
    mismatches = []
    for _, _, token in entries:
        if token.get('status') != 'implemented':
            continue
        value = actual.get(token['css'])
        if value is None or normalize(value) != normalize(token['value']):
            mismatches.append(token['css'])
    if mismatches:
        raise ValueError('Theme differs from approved design tokens: ' + ', '.join(mismatches))
    print('Implemented tokens match the local theme.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated files need rebuilding')
    parser.add_argument('--check-theme', action='store_true', help='Also compare implemented tokens with the local theme')
    args = parser.parse_args()
    generated, entries = outputs()
    if args.check_theme:
        check_theme(entries)
    for name, contents in generated.items():
        path = SOURCE / name
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8-sig') != contents:
                raise ValueError('Rebuild generated file: design-system/' + name)
        else:
            path.write_bytes(contents.encode('utf-8'))
    print('Design system is current.' if args.check else 'Built design-system/index.html and tokens.css.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        print('Design-system build failed: ' + str(error), file=sys.stderr)
        sys.exit(1)
